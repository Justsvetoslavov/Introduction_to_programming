#include <iostream>
using namespace std;

// В условието "стандартен символ" е всеки символ с код > 32.
// Следователно: c > 32  -> част от дума, c <= 32 -> разделител
bool isStandardChar(char c) {
    return c > 32;
}

// Отпечатва всички символи от интервала [begin, end).
// Функцията не променя нито един от указателите и не създава копие на думата.
void printWord(const char* begin, const char* end) {
    // Обхождаме точно символите на думата. Когато p == end, сме стигнали края на думата.
    for (const char* p = begin; p < end; ++p) {
        cout << *p;
    }
}

// Рекурсивна помощна функция. 
// Връща: true  -> ако е намерена и отпечатана поне една дума,
//        false -> ако в диапазона няма дума.
// Защо ни трябва bool? За да знаем дали вече сме отпечатали друга дума и съответно дали пред текущата дума трябва да сложим точно един интервал.
bool print_backwards_recursive(const char* begin, const char* end) {
    // Първо пропускаме всички разделители.
    // Например при: "   hello" begin първоначално сочи към интервалите. 
    // Преместваме го до 'h'. 
    // Проверяваме begin < end, защото end е граница на диапазона и не трябва да я преминаваме.
    while (begin < end && !isStandardChar(*begin)) {
        ++begin;
    }

    // Ако сме стигнали end, няма повече думи. Това е базовият случай на рекурсията.
    if (begin == end) {
        return false;
    }

    // begin вече сочи към първия символ на текущата дума. Сега намираме първия символ след нея. Този указател ще бъде wordEnd.
    const char* wordEnd = begin;

    while (wordEnd < end && isStandardChar(*wordEnd)) {
        ++wordEnd;
    }

    // В този момент: [begin, wordEnd) е текущата дума. wordEnd сочи: - към разделител след думата, или - към end, ако думата е последната.
    // Вместо да отпечатаме текущата дума веднага, първо рекурсивно обработваме всичко след нея. Това е същността на решението: последната дума ще бъде достигната първа при отпечатването при връщане от рекурсията.
    bool hasWordsAfter = print_backwards_recursive(wordEnd, end);

    // Ако има думи след текущата, те вече са отпечатани. Следователно пред текущата дума трябва да има точно един интервал. Например: текуща дума = "need" след нея = "a break!" Рекурсията първо отпечатва: break!
    // После тук слагаме: " " и отпечатваме: need
    if (hasWordsAfter) {
        cout << ' ';
    }

    // Накрая отпечатваме текущата дума. Понеже сме стигнали дотук чак след рекурсивното извикване, думите се получават в обратен ред.
    printWord(begin, wordEnd);

    // Вече сме отпечатали дума, затова връщаме true.
    return true;
}

// Функцията, изискана в условието: void print_backwards(const char* begin, const char* end); Тя просто стартира рекурсивния алгоритъм.
void print_backwards(const char* begin, const char* end) {
    print_backwards_recursive(begin, end);
}

// Еднопараметричната версия от условието.
// Тук string е C-style string, така че търсим неговия край чрез '\0'.
// Това е различно от двупараметричната версия: при [begin, end) нулевият символ може да бъде валиден елемент от буфера.
void print_backwards(const char* string) {
    const char* end = string;

    // Намираме края на C-string. След цикъла end сочи към '\0'. Именно този символ НЕ принадлежи на интервала [string, end).
    while (*end != '\0') {
        ++end;
    }

    // Извикваме рекурсивната версия с получените граници.
    print_backwards(string, end);
}

int main() {
    // Примерът от условието. Думите са: I need a break! Очакваме: break! a need I
    print_backwards("I\tneed a break!");
    cout << endl;

    return 0;
}