#include <iostream>
using namespace std;

// Проверява дали една въведена редица с n елемента образува аритметична прогресия.
// Важно: Функцията сама прочита елементите от входа. Не е необходимо да създаваме масив.
bool isArithmeticProgression(int n) {
    // Прочитаме първия елемент. Той е достатъчен за започване на проверката.
    int previous;
    cin >> previous;

    // При n == 1 имаме само един елемент.
    //  Една редица с един елемент може да се разглежда като аритметична прогресия, защото няма два съседни елемента, които да нарушат условието.
    if (n == 1) {
        return true;
    }

    // За n >= 2 прочитаме втория елемент. От първите два елемента определяме разликата.
    int current;
    cin >> current;

    // Използваме long long за изчисляването на разликата. 
    // Причината е, че ако current и previous са крайни int стойности, изваждането им като int може да доведе до signed overflow. 
    // Например: INT_MAX - INT_MIN не се побира в int. 
    // С long long самата разлика се представя безопасно.
    long long difference = static_cast<long long>(current) - previous;

    // След обработката на текущия елемент той става "предишен" за следващата стъпка.
    previous = current;

    // Засега приемаме, че редицата е аритметична. При първо нарушение ще го променим на false.
    bool arithmetic = true;

    // Остават елементите от третия до последния. За всеки от тях проверяваме дали: current - previous == difference Ако някъде това не е вярно, редицата вече не може да бъде аритметична.
    for (int i = 2; i < n; ++i) {
        cin >> current;

        // Отново първо преобразуваме current към long long, за да се извърши изваждането в по-широк тип.
        long long currentDifference = static_cast<long long>(current) - previous;

        // Ако разликата между две съседни стойности е различна от първоначално зададената разлика, редицата не е аритметична.
        if (currentDifference != difference) {
            arithmetic = false;
        }

        // Независимо дали е имало нарушение, current става предишен елемент за следващата итерация.
        previous = current;
    }

    return arithmetic;
}

// Обработва всички N редици и брои аритметичните.
// Не пазим нито една редица в паметта.
// Тази функция връща крайния брой.
int countArithmeticRows(int n) {
    int count = 0;

    // Има точно n редици. За всяка извикваме функцията за проверка.
    for (int row = 0; row < n; ++row) {
        if (isArithmeticProgression(n)) {
            ++count;
        }
    }

    return count;
}

int main() {
    // Първо прочитаме N. Според условието: 1 <= N <= 20
    int n;
    cin >> n;

    // Намираме броя на редиците, които са аритметични прогресии.
    cout << countArithmeticRows(n) << endl;

    return 0;
}